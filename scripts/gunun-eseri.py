def kimlik(eser: dict, icerik_sirasi: list[str], i: int) -> str:
    return eser.get("id") or icerik_sirasi[i]


def main() -> None:
    # Envanter künyesi araştırmada yoksa fotoğrafların alındığı PDF sayfaları
    # (data/gorseller.json, scripts/gorsel-ders.py ESLEME) künye olarak kullanılır.
    gorseller = json.loads((PROJE / "data" / "gorseller.json").read_text(encoding="utf-8"))
    cikti = []
    for dosya in sorted((PROJE / "data" / "research").glob("*.json")):
        arastirma = json.loads(dosya.read_text(encoding="utf-8"))["eserler"]
        icerik = json.loads((PROJE / "data" / "content" / dosya.name).read_text(encoding="utf-8"))
        sira = [d["eserId"] for d in icerik["dersler"]]
        for i, e in enumerate(arastirma):
            eid = kimlik(e, sira, i)
            assert eid == sira[i], (eid, sira[i])
            kategori, yil, yaklasik, kullanim, zaman, yaptiran = IPUCLARI[eid]
            kisa = re.sub(r"\s*\(.*\)\s*$", "", e["ad"]).strip()
            kaynak = next(
                (k["kunye"] for k in e["kaynaklar"] if k["kunye"].startswith("Vakıf Katılım")),
                gorseller.get(eid, {}).get("kaynak") or e["kaynaklar"][0]["kunye"],
            )
            cikti.append({
                "eserId": eid,
                "ad": e["ad"],
                "kisaAd": kisa,
                "sehir": e["sehir"],
                "kategori": kategori,
                "yil": yil,
                "yaklasik": yaklasik,
                "kullanim": kullanim,
                "zaman": zaman,
                "yaptiran": yaptiran,
                "kaynak": kaynak,
            })
    assert len(cikti) == len(IPUCLARI), "ipucu/araştırma sayısı tutmuyor"
    HEDEF.parent.mkdir(parents=True, exist_ok=True)
    HEDEF.write_text(json.dumps(cikti, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"✓ {len(cikti)} eser → {HEDEF.relative_to(PROJE)}")


if __name__ == "__main__":
    main()
